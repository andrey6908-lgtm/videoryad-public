# -*- coding: utf-8 -*-
"""КАРКАС АНАТОМИИ: учёт рук и сборка кадра в два прохода (R-0051).

Его слово 15.11.2026: «какие-то три руки… должны соответствовать механике,
физике, откуда у человека что растёт, биологии». Третья рука рождалась так:
сцена рисовала фигуру (у неё два своих рукава) и СВЕРХУ свою тянущуюся руку.

Лечение — два прохода на каждый кадр: первый запоминает, куда сцена крепит
внешние руки, второй рисует фигуру БЕЗ своего рукава на этом плече.

ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ МОДУЛЬ КАРКАСА, А НЕ ЧАСТЬ `lok_obshchee.py` (16.11.2026):
`lok.py` склеивается из сквозных образов и частей, и гейт заимствований
`svoi_kadry.py` сверяет ТЕЛА всех функций этого файла с прошлыми роликами.
Механика двух проходов у всех роликов проекта одна и та же — если держать её
в сквозных образах, она либо будет считаться заимствованием, либо её придётся
каждый раз переписывать другими словами. Поэтому механика живёт здесь (как
`baza.py` и `kamera.py`), а `lok.py` поднимает её себе в имена
(`from anat import *`), чтобы `kadr.py` по-прежнему звал `lok.scena(...)`,
а гейт `anatomiya.py` — `lok.anatomiya_svodka()`.
"""

_RUKI = []        # точки крепления внешних рук, набираются первым проходом
_SOBRANO = None   # готовый список для второго прохода (None = проход первый)
_NICH = []        # руки, объявленные ничьими (крупный план кистей)
_FIGURY = []      # (x, плечо, погашено, ширина, рост) — для гейта
_PRIKLEENO = []   # какие внешние руки сели на плечо фигуры — для гейта


def ruki_sbros():
    """Начать первый проход: забыть прежние руки."""
    global _RUKI, _SOBRANO
    _RUKI, _SOBRANO = [], None
    del _FIGURY[:], _PRIKLEENO[:], _NICH[:]


def ruki_gotovo():
    """Закрыть первый проход: со следующего вызова фигура прячет рукава."""
    global _SOBRANO
    _SOBRANO = list(_RUKI)
    del _FIGURY[:], _PRIKLEENO[:]     # фигуры первого прохода не считаем


def ruki_spisok():
    """Что собрано первым проходом (для гейта anatomiya.py)."""
    return list(_RUKI)


def pervyy_prohod():
    """Идёт первый проход? Только в нём руки запоминаются."""
    return _SOBRANO is None


def zapomnit_ruku(x, y, nichya=False):
    """Внешняя рука сцены: запомнить плечо, откуда она растёт.

    nichya=True — рука НИЧЬЯ: крупный план кистей, человека в кадре нет
    (рукав держит плечики, тянет чехол). Такая рука не гасит рукав соседней
    фигуры и третьей рукой в гейте не считается.
    """
    if _SOBRANO is None:
        (_NICH if nichya else _RUKI).append((x, y))


def ruki_na_pleche(rx, ry, dx, dy):
    """Внешние руки, севшие на это плечо; они же помечаются приклеенными.

    Вызывается фигурой во ВТОРОМ проходе: если список не пуст, свой рукав на
    этом плече не рисуется.
    """
    sel = [(hx, hy) for hx, hy in (_SOBRANO or ())
           if abs(hx - rx) <= dx and abs(hy - ry) <= dy]
    for r in sel:
        if r not in _PRIKLEENO:
            _PRIKLEENO.append(r)
    return sel


def uchest_figuru(x, plecho, pogasheno, w_, h_):
    """Фигура в кадре — для сводки гейта."""
    _FIGURY.append((x, plecho, pogasheno, w_, h_))


def anatomiya_svodka():
    """Для гейта: фигуры, внешние руки и руки, не севшие ни на одно плечо.

    Сирота ДЕЛИТСЯ НАДВОЕ, и это важно:
    · «на фигуре» — рука растёт из туловища мимо плеча. Это и есть третья
      рука (R-0051), сборка с такой рукой не идёт;
    · «вне фигур» — крупный план рукавов там, где человека в кадре нет
      (рукав снимает плечики с перекладины). Это норма, только отчёт.
    """
    siroty = [r for r in _RUKI if r not in _PRIKLEENO]
    na_figure = []
    for hx, hy in siroty:
        for fx, fpl, _p, w_, h_ in _FIGURY:
            if abs(hx - fx) <= w_ * .70 and -h_ * .10 <= hy - fpl <= h_ * .62:
                na_figure.append((hx, hy, fx, fpl))
                break
    return {"figur": len(_FIGURY), "ruk": len(_RUKI), "nichih": len(_NICH),
            "pogasheno": sum(f[2] for f in _FIGURY), "siroty": siroty,
            "na_figure": na_figure,
            "bez_svoih": [f for f in _FIGURY if f[2] >= 2]}


def scena(fn, t):
    """Собрать сцену в два прохода — иначе у фигуры вырастает третья рука."""
    ruki_sbros()
    fn(t)
    ruki_gotovo()
    out = fn(t)
    global _SOBRANO
    _SOBRANO = None
    return out
