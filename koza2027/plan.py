def frame_info(i):
    """По номеру кадра: сцена, локальное время, зум, якорь + сцена перехода."""
    t = i / FPS
    for k, (a, b, nm, z0, z1, cx, cy) in enumerate(SHOTS):
        if t < b - 1e-9 or k == len(SHOTS) - 1:
            u = (t - a) / max(1e-6, b - a)
            u = max(0.0, min(1.0, u))
            z = z0 + (z1 - z0) * u
            cur = (nm, t - a, z, cx, cy)
            left = b - t
            if k < len(SHOTS) - 1 and left < TRANS:
                nb = SHOTS[k + 1]
                zn = nb[3]
                mix = (TRANS - left) / TRANS
                return cur, (nb[2], 0.0, zn, nb[5], nb[6]), mix
            return cur, None, 0.0
    raise RuntimeError("кадр вне раскадровки: %d" % i)
